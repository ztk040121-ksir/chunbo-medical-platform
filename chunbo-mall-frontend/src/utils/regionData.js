/** 地址字符串拆分为 [省, 市, 区] 数组 */
export function splitRegionPrefix(address) {
  if (!address) return []
  const trimmed = address.trim()
  for (const [p, cities] of Object.entries(REGION_DATA)) {
    if (trimmed.startsWith(p)) {
      const restAfterP = trimmed.substring(p.length).trim()
      for (const [c, districts] of Object.entries(cities)) {
        if (restAfterP.startsWith(c)) {
          const restAfterC = restAfterP.substring(c.length).trim()
          for (const d of districts) {
            if (restAfterC.startsWith(d)) {
              return [p, c, d]
            }
          }
          return [p, c]
        }
      }
      return [p]
    }
  }
  return []
}
